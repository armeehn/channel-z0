def _bits(rows):
    return [[c == "#" for c in r] for r in rows]


SMALL = {ch: _bits(art.split("|")) for ch, art in _S.items()}

# A missing glyph must be loud, not invisible: an unmapped character in a
# caption is a typo I want to see in the first test frame, not a mystery gap.
MISSING = _bits(["######", "#....#", "#.##.#", "#.##.#", "#.##.#", "#....#", "######"])


def _validate():
    for ch, g in SMALL.items():
        assert len(g) == SMALL_H, (ch, len(g))
        for r in g:
            assert len(r) == SMALL_W, (ch, len(r))


_validate()
